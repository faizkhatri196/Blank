import { describe, it, expect, beforeEach, afterEach, vi } from 'vitest';
import fs from 'fs';
import path from 'path';

describe('Servora PWA Installation & Service Worker Tests', () => {
  const clientDir = path.resolve(__dirname, '../../../client');
  const publicDir = path.resolve(clientDir, 'public');
  const distDir = path.resolve(clientDir, 'dist');
  const manifestPath = path.resolve(publicDir, 'manifest.webmanifest');

  describe('1. Web App Manifest & Asset Verification', () => {
    it('manifest.webmanifest exists and contains valid required PWA metadata', () => {
      expect(fs.existsSync(manifestPath)).toBe(true);
      const content = JSON.parse(fs.readFileSync(manifestPath, 'utf-8'));

      expect(content.name).toBe('Servora — Smarter Field Service Operations');
      expect(content.short_name).toBe('Servora');
      expect(content.description).toContain('Field service management');
      expect(content.start_url).toBe('/');
      expect(content.scope).toBe('/');
      expect(content.display).toBe('standalone');
      expect(content.theme_color).toBe('#0f172a');
      expect(content.background_color).toBe('#f8fafc');
      expect(Array.isArray(content.icons)).toBe(true);
      expect(content.icons.length).toBeGreaterThanOrEqual(4);
    });

    it('all referenced manifest icons exist on disk with valid non-zero sizes', () => {
      const content = JSON.parse(fs.readFileSync(manifestPath, 'utf-8'));
      const requiredSizes = ['192x192', '512x512'];

      for (const icon of content.icons) {
        const iconFilename = path.basename(icon.src);
        const iconPath = path.resolve(publicDir, iconFilename);

        expect(fs.existsSync(iconPath), `Icon file ${iconFilename} should exist`).toBe(true);
        const stat = fs.statSync(iconPath);
        expect(stat.size).toBeGreaterThan(1000); // Must be a real non-empty image
      }

      // Verify maskable icon is declared
      const maskableIcon = content.icons.find((i: any) => i.purpose === 'maskable');
      expect(maskableIcon).toBeDefined();
      expect(maskableIcon.sizes).toBe('512x512');

      // Verify apple touch icon exists
      const appleTouchIconPath = path.resolve(publicDir, 'apple-touch-icon-180x180.png');
      expect(fs.existsSync(appleTouchIconPath)).toBe(true);
    });

    it('compatibility manifest.json matches manifest.webmanifest', () => {
      const compatJsonPath = path.resolve(publicDir, 'manifest.json');
      expect(fs.existsSync(compatJsonPath)).toBe(true);
      const webmanifest = JSON.parse(fs.readFileSync(manifestPath, 'utf-8'));
      const json = JSON.parse(fs.readFileSync(compatJsonPath, 'utf-8'));

      expect(json.name).toBe(webmanifest.name);
      expect(json.short_name).toBe(webmanifest.short_name);
      expect(json.start_url).toBe(webmanifest.start_url);
    });
  });

  describe('2. Service Worker & Workbox Security Configuration', () => {
    it('service worker output files exist in production build dist directory', () => {
      const swPath = path.resolve(distDir, 'sw.js');
      const registerSwPath = path.resolve(distDir, 'registerSW.js');
      const distManifestPath = path.resolve(distDir, 'manifest.webmanifest');

      expect(fs.existsSync(swPath), 'dist/sw.js must be generated by build').toBe(true);
      expect(fs.existsSync(registerSwPath), 'dist/registerSW.js must exist').toBe(true);
      expect(fs.existsSync(distManifestPath), 'dist/manifest.webmanifest must exist').toBe(true);
    });

    it('strictly avoids caching sensitive API endpoints (NetworkOnly for /api/*)', () => {
      const swPath = path.resolve(distDir, 'sw.js');
      const swContent = fs.readFileSync(swPath, 'utf-8');

      // Check Workbox NetworkOnly rule for /api
      expect(swContent).toContain('/api');
      expect(swContent).toContain('NetworkOnly');

      // Check navigateFallback denylist for /api/ and /uploads/
      expect(swContent).toContain('/^\\/api\\//');
      expect(swContent).toContain('/^\\/uploads\\//');

      // Check cleanupOutdatedCaches is called to prevent stale bundles
      expect(swContent).toContain('cleanupOutdatedCaches');
    });

    it('index.html links to manifest and registers service worker', () => {
      const indexPath = path.resolve(distDir, 'index.html');
      const html = fs.readFileSync(indexPath, 'utf-8');

      expect(html).toContain('rel="manifest"');
      expect(html).toContain('manifest.webmanifest');
      expect(html).toContain('name="theme-color"');
      expect(html).toContain('name="apple-mobile-web-app-capable"');
      expect(html).toContain('registerSW.js');
    });
  });

  describe('3. PWA Installation State Logic', () => {
    let mockLocalStorage: Record<string, string> = {};

    beforeEach(() => {
      mockLocalStorage = {};
    });

    it('detects standalone display mode (already installed application)', () => {
      const checkStandalone = (mediaMatch: boolean, iosStandalone: boolean, referrer: string) => {
        const isStandaloneMedia = mediaMatch;
        const isIOSStandalone = iosStandalone;
        const isTwa = referrer.startsWith('android-app://');
        return Boolean(isStandaloneMedia || isIOSStandalone || isTwa);
      };

      expect(checkStandalone(false, false, '')).toBe(false); // Normal browser
      expect(checkStandalone(true, false, '')).toBe(true);   // Desktop/Android standalone
      expect(checkStandalone(false, true, '')).toBe(true);   // iOS Safari standalone
      expect(checkStandalone(false, false, 'android-app://com.servora.twa')).toBe(true); // Android TWA
    });

    it('evaluates dismissal persistence and respects 7-day expiration', () => {
      const STORAGE_KEY = 'servora_pwa_dismissed_until';
      const SEVEN_DAYS_MS = 7 * 24 * 60 * 60 * 1000;

      const isDismissed = (now: number): boolean => {
        const stored = mockLocalStorage[STORAGE_KEY];
        if (!stored) return false;
        return now < parseInt(stored, 10);
      };

      const setDismissed = (now: number) => {
        mockLocalStorage[STORAGE_KEY] = (now + SEVEN_DAYS_MS).toString();
      };

      const now = 1700000000000;
      expect(isDismissed(now)).toBe(false);

      // User dismisses banner
      setDismissed(now);
      expect(isDismissed(now)).toBe(true);

      // 3 days later: still dismissed
      expect(isDismissed(now + 3 * 24 * 60 * 60 * 1000)).toBe(true);

      // 8 days later: expired, banner can be shown again
      expect(isDismissed(now + 8 * 24 * 60 * 60 * 1000)).toBe(false);
    });

    it('handles native beforeinstallprompt execution and outcome choices', async () => {
      let promptCalled = false;

      const mockPromptEvent = {
        prompt: vi.fn().mockImplementation(() => {
          promptCalled = true;
          return Promise.resolve();
        }),
        userChoice: Promise.resolve({ outcome: 'accepted' as const, platform: 'web' }),
      };

      await mockPromptEvent.prompt();
      const choice = await mockPromptEvent.userChoice;

      expect(promptCalled).toBe(true);
      expect(choice.outcome).toBe('accepted');
    });

    it('handles cancelled installation without errors or broken UI state', async () => {
      const mockPromptEvent = {
        prompt: vi.fn().mockResolvedValue(undefined),
        userChoice: Promise.resolve({ outcome: 'dismissed' as const, platform: 'web' }),
      };

      await mockPromptEvent.prompt();
      const choice = await mockPromptEvent.userChoice;

      expect(choice.outcome).toBe('dismissed');
      // Website continues functioning normally
    });

    it('determines platform-specific installation workflows (iOS vs Chromium vs Desktop)', () => {
      const detectPlatform = (ua: string, maxTouchPoints: number) => {
        const isIOS = (/iPad|iPhone|iPod/.test(ua) || (/MacIntel/.test(ua) && maxTouchPoints > 1));
        const isAndroid = /Android/i.test(ua);
        const isDesktop = !isIOS && !isAndroid;
        return { isIOS, isAndroid, isDesktop };
      };

      // iPhone Safari
      const iPhone = detectPlatform('Mozilla/5.0 (iPhone; CPU iPhone OS 16_5 like Mac OS X) AppleWebKit/605.1.15 Mobile/15E148 Safari/604.1', 5);
      expect(iPhone.isIOS).toBe(true);
      expect(iPhone.isDesktop).toBe(false);

      // Android Chrome
      const android = detectPlatform('Mozilla/5.0 (Linux; Android 13; Pixel 7) AppleWebKit/537.36 Chrome/114.0.0.0 Mobile Safari/537.36', 5);
      expect(android.isAndroid).toBe(true);
      expect(android.isIOS).toBe(false);

      // Desktop Chrome
      const desktop = detectPlatform('Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/120.0.0.0 Safari/537.36', 0);
      expect(desktop.isDesktop).toBe(true);
      expect(desktop.isIOS).toBe(false);
      expect(desktop.isAndroid).toBe(false);
    });
  });
});
